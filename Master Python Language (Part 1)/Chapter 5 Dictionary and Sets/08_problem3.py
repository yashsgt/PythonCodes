#  Can we have a set with 18(int) and '18' (str) as a value in it ?

s = set()
s.add(18)  # 18 as an integer.....
s.add("18")   # "18" as an string.....

print(s)

# Ans-> Yes, We can store 18 as an integer as well as an string in a set.

len(s)
print(len(s))  # len(s) is used to determine the length of a set.....

